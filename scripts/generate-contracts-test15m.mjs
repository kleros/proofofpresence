// A separate, Chiado-only rehearsal implementation. Production v8 is never rewritten.
import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
export const TEST15M_PROFILE = "kleros-event-v8-test15m";
export const TEST15M_VERSION = 80015;
export const TEST15M_CHAIN_ID = 10200;
export const TEST15M_PERIOD = 900;
export const PRODUCTION_SOURCE_SHA256 = Object.freeze({
  "KlerosEventV8.sol":
    "e97e3f9a4adb2bb4a697adac609367e5ad2103379bb395a241d54cedc62a9769",
  "KlerosEventFactoryV8.sol":
    "8488bb19f34f90c302afb08af99759b6308ef04199bc10dc973fa5ad35558505",
});
const sha256 = (value) => createHash("sha256").update(value).digest("hex");
const banner =
  "// GENERATED by scripts/generate-contracts-test15m.mjs; edit the generator, never this file.\n// CHIADO TEST ONLY: chain 10200; 15-minute challenge and match windows.\n// Financial logic is copied exactly from pinned production v8; production remains unchanged.\n";

function replaceExactly(source, from, to, expected = 1) {
  const count = source.split(from).length - 1;
  if (count !== expected)
    throw new Error(
      `Test15m transformation expected ${expected} matches for ${JSON.stringify(from)}, found ${count}`,
    );
  return source.split(from).join(to);
}

export function generatedTest15mSources() {
  return Object.entries(PRODUCTION_SOURCE_SHA256).map(
    ([filename, expectedHash]) => {
      const original = fs.readFileSync(
        path.join(root, "contracts", filename),
        "utf8",
      );
      if (sha256(original) !== expectedHash)
        throw new Error(
          `Pinned production source changed: ${filename}; review the test profile before regeneration`,
        );
      const child = filename === "KlerosEventV8.sol";
      let source = replaceExactly(
        original,
        "KlerosEventV8",
        "KlerosEventV8Test15m",
        child ? 2 : 4,
      );
      if (!child)
        source = replaceExactly(
          source,
          "KlerosEventFactoryV8",
          "KlerosEventFactoryV8Test15m",
        );
      source = replaceExactly(
        source,
        "uint256 public constant VERSION = 8;",
        "uint256 public constant VERSION = 80015;",
      );
      source = replaceExactly(
        source,
        "    error Reentrancy();",
        "    error Reentrancy();\n    error UnsupportedTestChain(uint256 chainId);",
      );
      if (child) {
        source = replaceExactly(
          source,
          "uint256 public constant CHALLENGE_PERIOD = 1 days;",
          "uint256 public constant CHALLENGE_PERIOD = 15 minutes;",
        );
        source = replaceExactly(
          source,
          "uint256 public constant MATCH_PERIOD = 1 days;",
          "uint256 public constant MATCH_PERIOD = 15 minutes;",
        );
        source = replaceExactly(
          source,
          "Opens the 1-day challenge window.",
          "Opens the 15-minute test challenge window.",
        );
        source = replaceExactly(
          source,
          "match its deposit within 1 day.",
          "match its deposit within 15 minutes (test only).",
        );
        source = replaceExactly(
          source,
          "    ) {\n        require(depositAmount_ > 0, ZeroDeposit());",
          "    ) {\n        require(block.chainid == 10200, UnsupportedTestChain(block.chainid));\n        require(depositAmount_ > 0, ZeroDeposit());",
        );
      } else {
        source = replaceExactly(
          source,
          "    constructor() {\n",
          "    constructor() {\n        require(block.chainid == 10200, UnsupportedTestChain(block.chainid));\n",
        );
      }
      const name = child
        ? "KlerosEventV8Test15m.sol"
        : "KlerosEventFactoryV8Test15m.sol";
      return {
        filename: `contracts/test/${name}`,
        content: banner + source,
        productionSource: `contracts/${filename}`,
        productionSha256: expectedHash,
      };
    },
  );
}

export function checkTest15mSources() {
  const sources = generatedTest15mSources();
  for (const { filename, content } of sources) {
    const target = path.join(root, filename);
    if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== content)
      throw new Error(
        `Generated test15m source drift: ${filename}; run node scripts/generate-contracts-test15m.mjs`,
      );
  }
  return sources;
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  if (
    process.argv.length > 3 ||
    (process.argv[2] && process.argv[2] !== "--check")
  )
    throw new Error(
      "Usage: node scripts/generate-contracts-test15m.mjs [--check]",
    );
  if (process.argv[2] === "--check") checkTest15mSources();
  else
    for (const { filename, content } of generatedTest15mSources()) {
      fs.mkdirSync(path.dirname(path.join(root, filename)), {
        recursive: true,
      });
      fs.writeFileSync(path.join(root, filename), content);
    }
  console.log(
    `Verified ${TEST15M_PROFILE}: pinned production logic, VERSION ${TEST15M_VERSION}, chain ${TEST15M_CHAIN_ID}, periods ${TEST15M_PERIOD}s`,
  );
}
